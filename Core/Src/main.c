/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_USART2_UART_Init();
  MX_CAN1_Init();
  MX_USART1_UART_Init();
  MX_TIM2_Init();

  /* USER CODE BEGIN 2 */
  UART_Comm_Init(&huart1);
  initCAN(&hcan1);
  init_ultrasonic_filters();
  /* USER CODE END 2 */
  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
while (1)
{
  // HAL_Delay(1000);
    switch (state)
    {
      case STATE_SEND_IMU:
      {
        if (imu_addresses[current_index] == 0x00)
        {
          state = STATE_PROCESS;
          break;
        }
        imu_data_fresh[current_index] = 0;
        Modbus_Send_Request(&huart1, imu_addresses[current_index]);
        imu_timestamp = HAL_GetTick();
        state = STATE_WAIT_IMU;
        break;
      }

      case STATE_WAIT_IMU:
      {
        if (imu_data_fresh[current_index] || (HAL_GetTick() - imu_timestamp) > IMU_TIMEOUT_MS)
        {
          imu_data_fresh[current_index] = 0;
          state = STATE_SEND_US;
        }
        break;
      }

      case STATE_SEND_US:
      {
        if (us_addresses[current_index] == 0x00)
        {
          state = STATE_PROCESS;
          break;
        }
        filtered_distance_fresh[current_index] = 0;
        HAL_Delay(1);
        Modbus_Send_Request(&huart1, us_addresses[current_index]);
        us_timestamp = HAL_GetTick();
        state = STATE_WAIT_US;
        break;
      }

      case STATE_WAIT_US:
      {
        if (filtered_distance_fresh[current_index] || (HAL_GetTick() - us_timestamp) > ULTRASONIC_TIMEOUT_MS)
        {
          filtered_distance_fresh[current_index] = 0;
          state = STATE_PROCESS;
        }
        break;
      }

      case STATE_PROCESS:
      {
        current_index++;
        if (current_index >= SENSOR_PAIR_COUNT)
        {
          current_index = 0;
          fuse_orientation(&imu_data[0], &imu_data[1], &imu_data[2], &fusedOrientation);

          float roll_from_ultra = roll_ultra(filtered_distance[0], filtered_distance[1], SENSOR_DISTANCE_MM);
          fusedOrientation.global_roll = fuse_roll(fusedOrientation.global_roll, roll_from_ultra);
          corrected_distance[0] = corrected_height(filtered_distance[0], fusedOrientation.global_roll, fusedOrientation.global_pitch);
          corrected_distance[1] = corrected_height(filtered_distance[1], fusedOrientation.global_roll, fusedOrientation.global_pitch);

          SendCANData(&hcan1, corrected_distance, &fusedOrientation);
        } 
        state = STATE_SEND_IMU;
        break;
      }

      default:
      {
        current_index = 0;
        state = STATE_SEND_IMU;
        break;
      }
    }
  }
  /* USER CODE END 3 */
}

